#!/usr/bin/env python3
"""One-table view of visibility.json (MAP.md holds the per-row detail and the rules).

    /usr/bin/python3 -B research/visibility-map/map_table.py > research/visibility-map/MAP_TABLE.md
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
FAM = ("L", "M", "S", "Tsel", "T")


def frac(kn):
    return "—" if kn is None else "%d/%d" % tuple(kn)


def fam(row, f):
    x = row["families"].get(f)
    if not x or not x.get("n"):
        return "—"
    own = " (own %d)" % x["own"] if x.get("own") else ""
    return "%d/%d%s" % (x["outside"], x["n"], own)


def flags(row):
    return ", ".join(sorted({b.split(":")[0] for b in row["byConstruction"]})) or ""


def main(path=HERE / "visibility.json"):
    d = json.loads(Path(path).read_text())
    out = ["# Fault visibility map, one table", "",
           "Generated by `research/visibility-map/map_table.py` from `visibility.json` (%s, framework %s). "
           "Rules, detectors and per-row sensors: `MAP.md`. Scope: instance per population." %
           (d.get("generatedAt", "?"), d.get("frameworkCommit", "?")[:7]), "",
           "Sensor cells: episodes caught by a sensor **outside** the faulted service / episodes whose posture collects "
           "that family; `(own k)` = caught by the faulted service's own sensors, excluded by G2. "
           "L logs, M container CPU, S cgroup system sampler, Tsel spans under `selected`, T spans under `full`. "
           "`—` = not collected or not recorded.", "",
           "| population | fault (target, kind) | n | request ledger | " + " | ".join(FAM) +
           " | class | caught by construction |",
           "|" + "---|" * (len(FAM) + 6)]
    for r in d["rows"]:
        ledger = frac(r["entryPoint"]) if not r["entryPointUnknown"] and r["entryPoint"] else "— (no ledger)"
        out.append("| %s | %s (%s, %s) | %d | %s | %s | %s | %s |" % (
            r["population"], r["faultClass"].replace("-effect", ""), r["target"], r["faultKind"], r["n"], ledger,
            " | ".join(fam(r, f) for f in FAM), r["visibilityClass"], flags(r)))
    out += ["", "Flag codes are defined in `MAP.md` (Rows caught by construction)."]
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    sys.stdout.write(main(*sys.argv[1:]))
