#!/usr/bin/env python3
"""Split the project map's undecided cells by what would make them decidable.

Reads project_map.json (window scope) and assigns every cell that is not yet decided a fix type, from the
reason string project_map.py wrote. The reason strings are project_map.py's own controlled vocabulary, so an
exact-prefix table is enough; an unmapped reason is reported as `?`, never silently folded.

Fix types (what kind of change resolves the cell):
  retain      the runtime already produces it; the harness does not keep it (no SUT change, nothing perturbed)
  sample      extend an existing collector to containers it skips (harness change, small host overhead)
  query       collected but queried or attributed too narrowly (collection/analysis change)
  instrument  needs new telemetry in the SUT (source/config change -> a posture, cost measured)
  exercise    the code path exists but the workload or fault never reached it (workload/catalogue change)
  project     the projection itself is unknown (source/config scan)
  confirm     not possible by configuration (no exporter, no metric library, tracer disabled), but no evidence
              confirms it (a posture proof or emission count would)

    uv run python research/project-map/decidability.py          # writes DECIDABILITY.md + decidability.png
    uv run python research/project-map/decidability.py --self-check
"""
import collections
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
FIX = (  # reason prefix -> fix type (project_map.py vocabulary)
    ("OTLP log records only", "retain"),
    ("container log not captured", "retain"),
    ("service log not captured", "retain"),
    ("container not sampled", "sample"),
    ("not counted by the harness CPU counters", "sample"),
    ("excluded from the cost probe", "sample"),
    ("Jaeger queried for service=frontend only", "query"),
    ("receiver-scraped metrics carry no service.name", "query"),
    ("collector self-metric resources", "query"),
    ("no application-metric collector", "instrument"),
    ("instrumented under this posture, but no data point", "instrument"),
    ("call sites exist but none fired", "exercise"),
    ("no traffic: not on the driven route", "exercise"),
    ("emitted only outside the measurement window", "exercise"),
    ("configured level unknown", "project"),
    ("no app call site at this level", "project"),
    ("no unlevelled output in this cell", "project"),
)
ORDER = ("retain", "sample", "query", "instrument", "exercise", "project", "confirm", "?")
COLOR = {"decided": "#b8b6ad", "retain": "#2a78d6", "sample": "#eb6834", "query": "#1baf7a",
         "instrument": "#eda100", "exercise": "#e87ba4", "project": "#008300", "confirm": "#9085e9", "?": "#6f6e66"}


def decided(cell):
    s = cell["state"]
    return s in ("possible-observed", "observed-not-projected") or (s == "not-possible" and not cell.get("unconfirmed"))


def fix_type(reason):
    for prefix, kind in FIX:
        if (reason or "").startswith(prefix):
            return kind
    return "?"


def split(doc):
    out = {}
    for sut, v in doc["suts"].items():
        c = collections.Counter()
        for cell in v["cells"]:
            if decided(cell):
                c["decided"] += 1
            elif cell["state"] == "not-possible" and cell.get("unconfirmed") and not cell.get("reason"):
                c["confirm"] += 1
            else:
                c[fix_type(cell.get("reason"))] += 1
        out[sut] = c
    return out


def render(doc, counts):
    lines = ["# Project map: what makes the undecided cells decidable", "",
             "Generated by `research/project-map/decidability.py` from `project_map.json` (%s, commit %s). Window scope; "
             "a cell is service x channel x posture. Research artefact, not for the paper; n = 1 cell per posture." %
             (doc.get("generatedAt", "?"), str(doc.get("gitCommit", "?"))[:7]), "",
             "| SUT | cells | decided | " + " | ".join(ORDER) + " |", "|" + "---|" * (len(ORDER) + 3)]
    for sut, c in counts.items():
        lines.append("| %s | %d | %d | %s |" % (sut, sum(c.values()), c["decided"],
                                               " | ".join(str(c[k]) if c[k] else "—" for k in ORDER)))
    lines += ["", "Fix types: retain = the runtime produces it but the harness does not keep it; sample = extend a collector "
              "to skipped containers; query = collected but queried/attributed too narrowly; instrument = needs new SUT "
              "telemetry (a posture, with its cost); exercise = workload or fault never reached the code path; project = "
              "the projection is unknown; confirm = not possible by configuration, not yet confirmed by evidence. `?` = reason not in the table (fix the table)."]
    return "\n".join(lines) + "\n"


def plot(counts, path):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    suts = list(counts)
    fig, ax = plt.subplots(figsize=(8, 2.6))
    for i, sut in enumerate(suts):
        total, left = sum(counts[sut].values()), 0.0
        for k in ("decided",) + ORDER:
            share = counts[sut][k] / total if total else 0
            if share:
                ax.barh(i, share, left=left, color=COLOR[k], edgecolor="white", linewidth=2, height=0.6)
                if share > 0.06:
                    ax.text(left + share / 2, i, "%s\n%d" % (k, counts[sut][k]), ha="center", va="center", fontsize=7,
                            color="black")
                left += share
    ax.set_yticks(range(len(suts)), ["%s (%d)" % (s, sum(counts[s].values())) for s in suts])
    ax.invert_yaxis()
    ax.set_xlim(0, 1)
    ax.set_xlabel("share of map cells (window scope)")
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)
    handles = [plt.Rectangle((0, 0), 1, 1, color=COLOR[k]) for k in ("decided",) + ORDER if any(c[k] for c in counts.values())]
    labels = [k for k in ("decided",) + ORDER if any(c[k] for c in counts.values())]
    ax.legend(handles, labels, ncol=len(labels), fontsize=7, frameon=False, loc="upper center", bbox_to_anchor=(0.5, 1.28))
    fig.tight_layout()
    fig.savefig(path, dpi=200)


def self_check():
    doc = {"suts": {"x": {"cells": [
        {"state": "possible-observed"},
        {"state": "not-possible"},
        {"state": "not-possible", "unconfirmed": True, "reason": "Jaeger queried for service=frontend only: x"},
        {"state": "unknown", "reason": "container log not captured by the Hotel harness"},
        {"state": "possible-not-observed", "reason": "call sites exist but none fired (x)"},
        {"state": "not-possible", "unconfirmed": True},
        {"state": "unknown", "reason": "something new"}]}}}
    c = split(doc)["x"]
    assert c == collections.Counter({"decided": 2, "query": 1, "retain": 1, "exercise": 1, "confirm": 1, "?": 1}), c
    print("self-check ok: 7 planted cells (decided x2, query, retain, exercise, confirm, unmapped)")


if __name__ == "__main__":
    if "--self-check" in sys.argv:
        self_check()
        sys.exit(0)
    doc = json.loads((HERE / "project_map.json").read_text())
    counts = split(doc)
    (HERE / "DECIDABILITY.md").write_text(render(doc, counts))
    plot(counts, HERE / "decidability.png")
    sys.stdout.write(render(doc, counts))
