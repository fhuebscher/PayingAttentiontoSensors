def exclusion(repo, path):
    """-> reason string if R7 excludes the file, else None."""
    parts = path.lower().split("/")
    name = parts[-1]
    ext = posixpath.splitext(name)[1]
    if any(p in VENDOR_DIRS for p in parts[:-1]) or name.endswith((".min.js", ".min.css")) or (
            name.endswith(".js") and repo.has(path[:-3] + ".min.js")):
        return "vendored"
    if any(p in TEST_DIRS for p in parts[:-1]) or "/src/test/" in "/" + path.lower():
        return "test"
    base = posixpath.basename(path)
    if (base.endswith("_test.go") or re.search(r"Tests?\.(java|kt|cs)$", base) or base.startswith("test_") and
            base.endswith(".py") or base.endswith("_test.py") or re.search(r"\.(test|spec)\.[a-z]+$", base) or
            "cypress" in name):
        return "test"
    if name.startswith(".") and name != ".env":
        return "tooling-dotfile"
    if ext in (".md", ".rst", ".adoc") or any(p in DOC_DIRS for p in parts[:-1]) or \
            re.match(r"(license|notice|changelog|authors|contributing)(\.|$)", name):
        return "doc"
    if name in LOCKFILES:
        return "lockfile"
    if ext in KEY_EXT:
        return "key-material"
    if ext in ASSET_EXT:
        return "asset"
    if base.endswith(GEN_SUFFIX):
        return "generated-stub"
    blob = repo.read(path)
    if b"\0" in blob[:8192]:
        return "asset"
    head = b"\n".join(blob.splitlines()[:5])
    if any(m.search(head) for m in GEN_MARKERS):
        return "generated-stub"
    return None

# ---------------------------------------------------------------------------------------------- YAML with lines


class Node:
    """A YAML node with its 1-based start line: .v is str | list[Node] | dict[str, (keyline, Node)]."""

    def __init__(self, v, line):
        self.v, self.line = v, line

    def get(self, k, default=None):
        if isinstance(self.v, dict) and k in self.v:
            return self.v[k][1]
        return default

    def keyline(self, k):
        return self.v[k][0]

    def plain(self):
        if isinstance(self.v, dict):
            return {k: n.plain() for k, (_, n) in self.v.items()}
        if isinstance(self.v, list):
            return [n.plain() for n in self.v]
        return self.v


def _conv(n, memo=None):
    memo = {} if memo is None else memo
    if id(n) in memo:
        return memo[id(n)]
    line = n.start_mark.line + 1
    if isinstance(n, yaml.MappingNode):
        out = Node({}, line)
        memo[id(n)] = out
        for kn, vn in n.value:
            if kn.tag == "tag:yaml.org,2002:merge":
                merged = _conv(vn, memo)
                for src in (merged.v if isinstance(merged.v, list) else [merged]):
                    for k, kv in src.v.items():
                        out.v.setdefault(k, kv)
                continue
            out.v[str(kn.value)] = (kn.start_mark.line + 1, _conv(vn, memo))
        return out
    if isinstance(n, yaml.SequenceNode):
        out = Node([], line)
        memo[id(n)] = out
        out.v.extend(_conv(x, memo) for x in n.value)
        return out
    return Node("" if n.value is None else str(n.value), line)


def load_yaml(text):
    n = yaml.compose(text, Loader=yaml.SafeLoader)
    return _conv(n) if n is not None else Node({}, 1)

# ---------------------------------------------------------------------------------------------- .env + interpolation


def load_env(repo, path):
    """{NAME: (value, line)} of a Compose .env file (KEY=VALUE, '#' comments, optional quotes)."""
    out = {}
    for i, raw in enumerate(repo.text(path).splitlines(), 1):
        s = raw.strip()
        if not s or s.startswith("#") or "=" not in s:
            continue
        k, v = s.split("=", 1)
        v = v.strip()
        if len(v) >= 2 and v[0] == v[-1] and v[0] in "'\"":
            v = v[1:-1]
        out[k.strip()] = (v, i)
    return out


_VAR = re.compile(r"\$\$|\$\{([A-Za-z_][A-Za-z0-9_]*)(?:(:?[-?])([^}]*))?\}|\$([A-Za-z_][A-Za-z0-9_]*)")


def interpolate(s, env, used=None, unresolved=None, depth=0):
    """Compose interpolation against env {NAME: (value, line)}; records used (name, line) and unresolved names."""
    used = [] if used is None else used
    unresolved = [] if unresolved is None else unresolved

    def rep(m):
        if m.group(0) == "$$":
            return "$"
        name = m.group(1) or m.group(4)
        op, arg = m.group(2), m.group(3)
        if name in env and not (op and op.startswith(":") and env[name][0] == ""):
            used.append((name, env[name][1]))
            v = env[name][0]
            return interpolate(v, env, used, unresolved, depth + 1)[0] if depth < 8 else v
        if op in (":-", "-"):
            return interpolate(arg, env, used, unresolved, depth + 1)[0]
        unresolved.append(name)
        return m.group(0)

    return _VAR.sub(rep, s), used, unresolved

# ---------------------------------------------------------------------------------------------- compose model


class Loc(dict):
    """A value with its citation: {'value', 'repo', 'file', 'line', 'raw'} (raw = the cited source line)."""


def _loc(repo, file, line, value, lines):
    return Loc(value=value, repo=repo, file=file, line=line, raw=lines[line - 1].strip() if 0 < line <= len(lines) else "")


class Compose:
    """Merged compose model of one system. services[name] = dict of Locs / lists of Locs."""

    def __init__(self, system, repos):
        cfg = SYSTEMS[system]
        self.system, self.repos = system, repos
        self.env = {}
        self.env_src = {}
        for rk, p in cfg["env"]:
            e = load_env(repos[rk], p)
            self.env.update(e)
            for k in e:
                self.env_src[k] = (rk, p)
        self.project_repo, first = cfg["compose"][0]
        self.project_dir = posixpath.dirname(first)
        self.services, self.order, self.configs, self.unresolved = {}, [], {}, set()
        for rk, p in cfg["compose"]:
            self._merge_file(rk, p)

    def interp(self, s):
        v, used, unres = interpolate(s, self.env)
        self.unresolved.update(unres)
        return v, used, unres

    def _merge_file(self, rk, path):
        lines = self.repos[rk].text(path).splitlines()
        doc = load_yaml(self.repos[rk].text(path))
        L = lambda line, value: _loc(rk, path, line, value, lines)
        cfgs = doc.get("configs")
        if cfgs is not None:
            for name, (kl, n) in cfgs.v.items():
                if n.get("file") is not None:
                    self.configs[name] = L(n.get("file").line, n.get("file").v)
        svcs = doc.get("services")
        if svcs is None:
            return
        for name, (kl, n) in svcs.v.items():
            if name not in self.services:
                self.services[name] = {"key": L(kl, name), "environment": {}, "volumes": [], "configs": [],
                                       "depends_on": [], "files": []}
                self.order.append(name)
            s = self.services[name]
            s["files"].append(L(kl, name))
            for k in ("image", "container_name", "hostname", "scale"):
                if n.get(k) is not None and isinstance(n.get(k).v, str):
                    s[k] = L(n.get(k).line, n.get(k).v)
            for k in ("entrypoint", "command"):
                if n.get(k) is not None:
                    x = n.get(k)
                    s[k] = L(x.line, x.plain())
            b = n.get("build")
            if b is not None:
                if isinstance(b.v, str):
                    s["build_context"] = L(b.line, b.v)
                else:
                    if b.get("context") is not None:
                        s["build_context"] = L(b.get("context").line, b.get("context").v)
                    if b.get("dockerfile") is not None:
                        s["dockerfile"] = L(b.get("dockerfile").line, b.get("dockerfile").v)
                    s.setdefault("build_context", L(b.line, "."))
            d = n.get("deploy")
            if d is not None and d.get("replicas") is not None:
                s["replicas"] = L(d.get("replicas").line, d.get("replicas").v)
            hc = n.get("healthcheck")
            if hc is not None:
                t = hc.get("test")
                s["healthcheck"] = L((t or hc).line, (t or hc).plain())
                for k in ("interval", "timeout", "retries", "start_period"):
                    if hc.get(k) is not None:
                        s.setdefault("healthcheck_params", {})[k] = L(hc.get(k).line, hc.get(k).v)
            env = n.get("environment")
            if env is not None:
                if isinstance(env.v, list):
                    for e in env.v:
                        k, _, v = e.v.partition("=")
                        s["environment"][k.strip()] = L(e.line, v if "=" in e.v else None)
                elif isinstance(env.v, dict):
                    for k, (kl2, vn) in env.v.items():
                        s["environment"][k] = L(kl2, vn.v if isinstance(vn.v, str) else None)
            dep = n.get("depends_on")
            if dep is not None:
                items = [(x.line, x.v) for x in dep.v] if isinstance(dep.v, list) else \
                    [(kl2, k) for k, (kl2, _) in dep.v.items()]
                for line, dn in items:
                    cond = None
                    if isinstance(dep.v, dict) and dep.get(dn).get("condition") is not None:
                        cond = dep.get(dn).get("condition").v
                    s["depends_on"].append(L(line, {"service": dn, "condition": cond}))
            vols = n.get("volumes")
            if vols is not None:
                for x in vols.v:
                    if isinstance(x.v, str):
                        s["volumes"].append(L(x.line, x.v))
                    elif x.get("source") is not None:
                        s["volumes"].append(L(x.get("source").line, "%s:%s" % (x.get("source").v,
                                                                                (x.get("target") or Node("", 0)).v)))
            cf = n.get("configs")
            if cf is not None:
                for x in cf.v:
                    src = x.v if isinstance(x.v, str) else (x.get("source").v if x.get("source") is not None else None)
                    if src:
                        s["configs"].append(L(x.line, src))
            nets = n.get("networks")
            if nets is not None and isinstance(nets.v, dict):
                for _, (_, nn) in nets.v.items():
                    if isinstance(nn.v, dict) and nn.get("aliases") is not None:
                        s.setdefault("aliases", []).extend(L(a.line, a.v) for a in nn.get("aliases").v)

    def resolve_path(self, p):
        """A compose-relative host path -> (repo key, repo-relative path) or None if outside the project tree."""
        if p.startswith("/") or p.startswith("~") or "$" in p:
            return None
        q = posixpath.normpath(posixpath.join(self.project_dir, p))
        if q.startswith(".."):
            return None
        return (self.project_repo, "" if q == "." else q)

    def aliases(self):
        """{alias: service} for every name compose declares for a service (key, container_name, hostname, aliases)."""
        out = {}
        for name in self.order:
            s = self.services[name]
            out[name] = name
        for name in self.order:
            s = self.services[name]
            for k in ("container_name", "hostname"):
                if k in s:
                    v = self.interp(s[k]["value"])[0]
                    # A hostname shared by several services (Hotel's memcached 'user-memcached') names none of them.
                    clash = [o for o in self.order if o != name and any(
                        k2 in self.services[o] and self.interp(self.services[o][k2]["value"])[0] == v
                        for k2 in ("container_name", "hostname"))]
                    if not clash:
                        out.setdefault(v, name)
            for a in s.get("aliases", []):
                out.setdefault(a["value"], name)
        return out

# ---------------------------------------------------------------------------------------------- Dockerfiles


def dockerfile_instructions(text):
    """[(instruction, args, first line)] with continuations joined and comments dropped."""
    out, buf, start = [], "", None
    for i, raw in enumerate(text.splitlines(), 1):
        s = raw.rstrip()
        if not buf and (not s.strip() or s.strip().startswith("#")):
            continue
        if buf and s.strip().startswith("#"):
            continue
        if start is None:
            start = i
        if s.endswith("\\"):
            buf += s[:-1] + " "
            continue
        buf += s
        parts = buf.strip().split(None, 1)
        out.append((parts[0].upper(), parts[1] if len(parts) > 1 else "", start))
        buf, start = "", None
    return out


def copy_sources(text):
    """[(source, line)] of in-context sources of COPY/ADD and RUN --mount=type=bind; and [(image, line)] of FROM."""
    srcs, froms = [], []
    for ins, args, line in dockerfile_instructions(text):
        if ins == "FROM":
            toks = [t for t in args.split() if not t.startswith("--")]
            if toks:
                froms.append((toks[0], line))
        elif ins in ("COPY", "ADD"):
            a = args.strip()
            flags = []
            while a.startswith("--"):
                f, _, a = a.partition(" ")
                flags.append(f)
                a = a.strip()
            if any(f.startswith("--from") for f in flags):
                continue
            if a.startswith("["):
                try:
                    toks = json.loads(a)
                except ValueError:
                    continue
            else:
                toks = a.split()
            for t in toks[:-1]:
                if "://" in t or "$" in t:
                    continue
                srcs.append((t, line))
        elif ins == "RUN":
            for m in re.finditer(r"--mount=(\S+)", args):
                kv = dict(x.split("=", 1) for x in m.group(1).split(",") if "=" in x)
                if kv.get("type") == "bind" and "source" in kv and "from" not in kv:
                    srcs.append((kv["source"], line))
    return srcs, froms


def dockerignore(repo, ctx):
    p = posixpath.join(ctx, ".dockerignore") if ctx else ".dockerignore"
    if not repo.has(p):
        return []
    pats = []
    for raw in repo.text(p).splitlines():
        s = raw.strip()
        if not s or s.startswith("#"):
            continue
        neg = s.startswith("!")
        s = s[1:] if neg else s
        s = s[2:] if s.startswith("./") else s
        pats.append((neg, s.strip("/")))
    return pats


def _ignored(rel, pats):
    hit = False
    for neg, p in pats:
        if fnmatch.fnmatchcase(rel, p) or rel.startswith(p + "/") or fnmatch.fnmatchcase(rel, p + "/*"):
            hit = not neg
    return hit


def expand_source(repo, ctx, src, pats):
    """Git paths a Dockerfile source (relative to the context; '/' = context root) denotes."""
    s = src.strip()
    s = s[2:] if s.startswith("./") else s
    s = s.lstrip("/")
    s = s.rstrip("/") if s not in ("", ".") else ""
    base = posixpath.normpath(posixpath.join(ctx, s)) if s else (ctx or "")
    base = "" if base == "." else base
    files = []
    if any(c in s for c in "*?["):
        # a glob matches files, or directories whose files are then all copied
        files = [p for p in repo.tree() if fnmatch.fnmatchcase(p, base) or
                 any(fnmatch.fnmatchcase(p[:j], base) for j, c in enumerate(p) if c == "/")]
    elif repo.has(base):
        files = [base]
    else:
        files = repo.files_under(base)
    out = []
    for f in sorted(set(files)):
        rel = f[len(ctx) + 1:] if ctx and f.startswith(ctx + "/") else (f if not ctx else None)
        if rel is None:
            continue
        if not _ignored(rel, pats):
            out.append(f)
    return out


def image_build_map(system, repos):
    """{image repository -> (repo key, context dir)} from the system's upstream image-build script (R2)."""
    spec = SYSTEMS[system]["imageBuildScript"]
    if not spec:
        return {}, None
    rk, path = spec
    text = repos[rk].text(path)
    out = {}
    reg = None
    for i, line in enumerate(text.splitlines(), 1):
        m = re.match(r"\s*registry='([^']*)'", line)
        if m:
            reg = m.group(1)
        m = re.search(r'-t\s+"\$\{registry\}([^"]+)"\s+(\S+)', line)
        if m and "--load" in line and reg is not None:
            ctx = posixpath.normpath(posixpath.join(posixpath.dirname(path), m.group(2)))
            out[reg + m.group(1)] = (rk, ctx, i)
    return out, (rk, path)

# ---------------------------------------------------------------------------------------------- Maven (R4)


def _pom(repo, path):
    t = ET.fromstring(repo.read(path))
    ns = {"m": t.tag[1:].split("}")[0]} if t.tag.startswith("{") else {}
    q = (lambda tag: "m:" + tag) if ns else (lambda tag: tag)
    def txt(el, tag):
        x = el.find(q(tag), ns)
        return x.text.strip() if x is not None and x.text else None
    par = t.find(q("parent"), ns)
    gid = txt(t, "groupId") or (txt(par, "groupId") if par is not None else None)
    deps = []
    dd = t.find(q("dependencies"), ns)
    if dd is not None:
        for d in dd.findall(q("dependency"), ns):
            deps.append((txt(d, "groupId"), txt(d, "artifactId")))
    mods = []
    mm = t.find(q("modules"), ns)
    if mm is not None:
        mods = [m.text.strip() for m in mm.findall(q("module"), ns) if m.text]
    rel = txt(par, "relativePath") if par is not None else None
    return {"groupId": gid, "artifactId": txt(t, "artifactId"), "deps": deps, "modules": mods,
            "parentRelativePath": rel if par is not None else None, "hasParent": par is not None}


def maven_closure(repo, module_dir):
    """Files of a Maven module + reactor dependency closure + parent pom chain (R4); and the module dirs used."""
    root = _pom(repo, "pom.xml") if repo.has("pom.xml") else None
    reactor = {}
    if root:
        for m in root["modules"]:
            d = posixpath.normpath(m)
            if repo.has(posixpath.join(d, "pom.xml")):
                p = _pom(repo, posixpath.join(d, "pom.xml"))
                reactor[(p["groupId"] or root["groupId"], p["artifactId"])] = d
    seen, todo = [], [posixpath.normpath(module_dir)]
    while todo:
        d = todo.pop(0)
        if d in seen:
            continue
        seen.append(d)
        p = _pom(repo, posixpath.join(d, "pom.xml"))
        for g, a in p["deps"]:
            if (g, a) in reactor:
                todo.append(reactor[(g, a)])
    files = set()
    for d in seen:
        files.update(f for f in repo.files_under(d) if not ("/" + f).count("/src/test/"))
        # parent chain (relativePath default ../pom.xml)
        cur = d
        p = _pom(repo, posixpath.join(cur, "pom.xml"))
        while p["hasParent"]:
            rp = p["parentRelativePath"] or "../pom.xml"
            pp = posixpath.normpath(posixpath.join(cur, rp))
            if not pp.endswith(".xml"):
                pp = posixpath.join(pp, "pom.xml")
            if pp.startswith("..") or not repo.has(pp):
                break
            files.add(pp)
            cur = posixpath.dirname(pp)
            p = _pom(repo, pp)
    return sorted(files), seen

# ---------------------------------------------------------------------------------------------- Go (R5)


def go_imports(src):
    """Import paths of one Go file (tree-sitter)."""
    from tree_sitter_language_pack import get_parser
    tree = get_parser("go").parse(src)
    out = []
    stack = [tree.root_node]
    while stack:
        n = stack.pop()
        if n.type == "import_spec":
            p = n.child_by_field_name("path")
            if p is not None:
                out.append(p.text.decode().strip('"`'))
            continue
        if n.type in ("function_declaration", "method_declaration", "type_declaration"):
            continue
        stack.extend(n.children)
    return out


def go_closure(repo, files, entry_dir, module_root):
    """Go files of `files` in the in-module import closure of package dir entry_dir."""
    gomod = posixpath.join(module_root, "go.mod") if module_root else "go.mod"
    mod = re.search(r"^module\s+(\S+)", repo.text(gomod), re.M).group(1)
    by_dir = {}
    for f in files:
        if f.endswith(".go"):
            by_dir.setdefault(posixpath.dirname(f), []).append(f)
    seen, todo = set(), [entry_dir]
    while todo:
        d = todo.pop()
        if d in seen:
            continue
        seen.add(d)
        for f in by_dir.get(d, []):
            for imp in go_imports(repo.read(f)):
                if imp == mod or imp.startswith(mod + "/"):
                    rel = imp[len(mod):].lstrip("/")
                    todo.append(posixpath.normpath(posixpath.join(module_root, rel)) if rel else module_root)
    keep = [f for d in sorted(seen) for f in by_dir.get(d, [])]
    return keep, sorted(seen), set(by_dir)

# ---------------------------------------------------------------------------------------------- bundles


def _entry_name(s):
    ep = s.get("entrypoint") or s.get("command")
    if not ep:
        return None
    v = ep["value"]
    if isinstance(v, list):
        v = v[0] if v else None
    return v.split()[0] if isinstance(v, str) and v.split() else None


def service_bundles(system, repos=None, compose=None):
    """-> (compose, {service: bundle dict}). Bundle files are (repo key, path)."""
    repos = repos or open_repos(system)
    comp = compose or Compose(system, repos)
    bmap, bscript = image_build_map(system, repos)
    up = comp.project_repo
    bundles = {}
    shared = {}

    def built_files(rk, ctx, dockerfile, rules, depth=0):
        repo = repos[rk]
        files = [(rk, dockerfile)]
        pats = dockerignore(repo, ctx)
        srcs, froms = copy_sources(repo.text(dockerfile))
        copied = []
        for src, _ in srcs:
            copied += expand_source(repo, ctx, src, pats)
        copied = sorted(set(copied))
        if copied:
            rules.append("R3b:%s" % dockerfile)
        elif repo.has(posixpath.join(ctx, "pom.xml")):
            mf, mods = maven_closure(repo, ctx)
            copied = mf
            rules.append("R4:%s" % ",".join(mods))
        files += [(rk, f) for f in copied]
        for img, _ in froms:
            base = img.split("@")[0].rsplit(":", 1)[0] if ":" in img.split("/")[-1] else img.split("@")[0]
            if base in bmap and depth < 4:
                brk, bctx, _ = bmap[base]
                rules.append("R3d:%s" % base)
                files += built_files(brk, bctx, posixpath.join(bctx, "Dockerfile"), rules, depth + 1)
        return files

    for name in comp.order:
        s = comp.services[name]
        rules, files, b = [], [], {"service": name}
        if "build_context" in s:
            ctx_raw = comp.interp(s["build_context"]["value"])[0]
            rp = comp.resolve_path(ctx_raw)
            ctx = rp[1]
            df_raw = comp.interp(s["dockerfile"]["value"])[0] if "dockerfile" in s else "Dockerfile"
            df = posixpath.normpath(posixpath.join(ctx, df_raw.lstrip("./") if df_raw.startswith("./") else df_raw))
            if df_raw.startswith("./"):
                df = posixpath.normpath(posixpath.join(ctx, df_raw[2:]))
            b.update(kind="built", buildContext={"repo": up, "path": ctx or "."}, dockerfile={"repo": up, "path": df})
            rules.append("R2:compose-build")
            files = built_files(up, ctx, df, rules)
            shared.setdefault((ctx, df), []).append(name)
        else:
            img = comp.interp(s.get("image", {}).get("value", ""))[0]
            base = img.split("@")[0]
            base = base.rsplit(":", 1)[0] if ":" in base.split("/")[-1] else base
            if base in bmap:
                brk, ctx, line = bmap[base]
                b.update(kind="built", buildContext={"repo": brk, "path": ctx},
                         dockerfile={"repo": brk, "path": posixpath.join(ctx, "Dockerfile")},
                         buildScript={"repo": bscript[0], "path": bscript[1], "line": line})
                rules.append("R2:image-build-script")
                files = built_files(brk, ctx, posixpath.join(ctx, "Dockerfile"), rules)
            else:
                b.update(kind="image-only", image=img)
                rules.append("R6")
        # R3(e): mounted in-tree files
        for v in s["volumes"]:
            host = comp.interp(v["value"].split(":")[0])[0]
            rp = comp.resolve_path(host)
            if rp:
                fs = [rp[1]] if repos[rp[0]].has(rp[1]) else repos[rp[0]].files_under(rp[1]) if rp[1] else []
                if fs:
                    rules.append("R3e:volume:%s" % host)
                files += [(rp[0], f) for f in fs]
        for c in s["configs"]:
            if c["value"] in comp.configs:
                rp = comp.resolve_path(comp.configs[c["value"]]["value"])
                if rp and repos[rp[0]].has(rp[1]):
                    rules.append("R3e:config:%s" % c["value"])
                    files.append(rp)
        b["rules"], b["_files"] = rules, files
        bundles[name] = b

    # R5: a shared image (same context + Dockerfile) for several services -> Go import closure per entrypoint
    for (ctx, df), names in shared.items():
        if len(names) < 2:
            continue
        repo = repos[up]
        if not repo.has(posixpath.join(ctx, "go.mod") if ctx else "go.mod"):
            continue
        for name in names:
            b = bundles[name]
            ent = _entry_name(comp.services[name])
            gofiles = [f for rk, f in b["_files"] if rk == up and f.endswith(".go")]
            mains = {posixpath.dirname(f) for f in gofiles if posixpath.basename(posixpath.dirname(f)) == ent
                     and re.search(rb"^package main\b", repo.read(f), re.M)}
            if len(mains) != 1:
                b["rules"].append("R5:no-unique-main-for-%s" % ent)
                continue
            keep, dirs, godirs = go_closure(repo, gofiles, mains.pop(), ctx)
            kept = set(keep)
            b["_files"] = [(rk, f) for rk, f in b["_files"] if not (rk == up and (
                (f.endswith(".go") and f not in kept) or
                (not f.endswith(".go") and posixpath.dirname(f) in godirs and posixpath.dirname(f) not in dirs)))]
            b["rules"].append("R5:go-closure:%s" % ",".join(dirs))
    return comp, bundles


def finalize(system, repos, bundles):
    """Apply R7, hash, and return manifest pieces."""
    excluded = {}
    cache = {}
    for name, b in bundles.items():
        df = b.get("dockerfile")
        keep = []
        for rk, f in dict.fromkeys(b.pop("_files")):
            is_df = df is not None and f.endswith("Dockerfile") and (rk, f) in {(df["repo"], df["path"])} or \
                posixpath.basename(f) == "Dockerfile"
            key = (rk, f)
            if key not in cache:
                why = None if is_df else exclusion(repos[rk], f)
                cache[key] = why
            why = cache[key]
            if why:
                excluded.setdefault(why, set()).add(key)
                continue
            blob = repos[rk].read(f)
            keep.append({"repo": rk, "path": f, "sha256": sha256(blob), "bytes": len(blob)})
        b["files"] = sorted(keep, key=lambda x: (x["repo"], x["path"]))
        b["fileCount"] = len(keep)
        b["bytes"] = sum(x["bytes"] for x in keep)
    return {k: sorted("%s:%s" % x for x in v) for k, v in sorted(excluded.items())}


def deployment_files(system, repos):
    cfg = SYSTEMS[system]
    out = []
    for role, items in (("compose", cfg["compose"]), ("env", cfg["env"]), ("deployment", cfg["otherDeployment"])):
        for rk, p in items:
            blob = repos[rk].read(p)
            out.append({"role": role, "repo": rk, "path": p, "sha256": sha256(blob), "bytes": len(blob)})
    if cfg["imageBuildScript"]:
        rk, p = cfg["imageBuildScript"]
        blob = repos[rk].read(p)
        out.append({"role": "image-build-script", "repo": rk, "path": p, "sha256": sha256(blob), "bytes": len(blob)})
    rk, p = HOST_TOPOLOGY
    blob = repos[rk].read(p)
    out.append({"role": "host-topology", "repo": rk, "path": p, "sha256": sha256(blob), "bytes": len(blob)})
    return out


def build_manifest(system, root=ROOT):
    repos = open_repos(system, root)
    comp, bundles = service_bundles(system, repos)
    excluded = finalize(system, repos, bundles)
    dep = deployment_files(system, repos)
    union = {}
    for d in dep:
        union[(d["repo"], d["path"])] = {k: d[k] for k in ("repo", "path", "sha256", "bytes")}
    for b in bundles.values():
        for f in b["files"]:
            union[(f["repo"], f["path"])] = f
    srcs = {k: {"path": r.relpath, "commit": r.commit, "pinnedAs": r.pinned_as} for k, r in repos.items()}
    return {
        "manifestVersion": 1,
        "system": system,
        "sources": srcs,
        "rules": "research/ontology/inputs.py module docstring, R1-R7",
        "deploymentFiles": dep,
        "services": {n: bundles[n] for n in comp.order},
        "files": [union[k] for k in sorted(union)],
        "fileCount": len(union),
        "bytes": sum(f["bytes"] for f in union.values()),
        "excluded": {k: {"count": len(v), "files": v} for k, v in excluded.items()},
        "unresolvedVariables": sorted(comp.unresolved),
    }


def summary(m):
    rows = ["%-24s %-10s %5s %9s  %s" % ("service", "kind", "files", "bytes", "rules")]
    for n, b in m["services"].items():
        rows.append("%-24s %-10s %5d %9d  %s" % (n, b["kind"], b["fileCount"], b["bytes"], " ".join(b["rules"])))
    rows.append("system %s: %d files, %d bytes in the manifest; deployment files %d; excluded %s" % (
        m["system"], m["fileCount"], m["bytes"], len(m["deploymentFiles"]),
        {k: v["count"] for k, v in m["excluded"].items()}))
    return "\n".join(rows)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("system", choices=sorted(SYSTEMS))
    ap.add_argument("--json", action="store_true")
    a = ap.parse_args(argv)
    m = build_manifest(a.system)
    print(json.dumps(m, indent=1) if a.json else summary(m))


if __name__ == "__main__":
    main()
