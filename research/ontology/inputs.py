# ---------------------------------------------------------------------------------------------- git access


class Repo:
    """Read-only view of one git repository at one pinned commit."""

    def __init__(self, key, path, commit, root=ROOT):
        p = Path(path)
        self.key, self.relpath = key, path
        self.wd = p if p.is_absolute() else (Path(root) / p)
        r = subprocess.run(["git", "-C", str(self.wd), "rev-parse", "--verify", commit + "^{commit}"],
                           capture_output=True, text=True)
        if r.returncode != 0:
            raise SystemExit("cannot resolve commit %s in %s: %s" % (commit, self.wd, r.stderr.strip()))
        self.commit = r.stdout.strip()
        if commit != "HEAD" and not self.commit.startswith(commit):
            raise SystemExit("commit %s resolved to %s" % (commit, self.commit))
        self.pinned_as = commit
        self._tree = None
        self._blobs = {}

    def tree(self):
        """{path: (blob sha1, size)} of every tracked file at the commit."""
        if self._tree is None:
            out = subprocess.run(["git", "-C", str(self.wd), "ls-tree", "-r", "-l", "-z", self.commit],
                                 capture_output=True, check=True).stdout.decode("utf-8", "replace")
            t = {}
            for rec in out.split("\0"):
                if not rec:
                    continue
                meta, path = rec.split("\t", 1)
                mode, typ, sha, size = meta.split()
                if typ == "blob":
                    t[path] = (sha, int(size) if size != "-" else 0)
            self._tree = t
        return self._tree

    def has(self, path):
        return path in self.tree()

    def read(self, path):
        if path not in self._blobs:
            r = subprocess.run(["git", "-C", str(self.wd), "show", "%s:%s" % (self.commit, path)], capture_output=True)
            if r.returncode != 0:
                raise FileNotFoundError("%s absent at %s in %s" % (path, self.commit[:12], self.key))
            self._blobs[path] = r.stdout
        return self._blobs[path]

    def text(self, path):
        return self.read(path).decode("utf-8", "replace")

    def files_under(self, d):
        d = d.strip("/")
        if d in ("", "."):
            return sorted(self.tree())
        return sorted(p for p in self.tree() if p == d or p.startswith(d + "/"))


def sha256(b):
    return hashlib.sha256(b).hexdigest()


